    public void generateStockPDFReport(String fileName) {
       try (PdfWriter writer = new PdfWriter(fileName + ".pdf");
            PdfDocument pdf = new PdfDocument(writer);
            Document document = new Document(pdf)) {
 
           // Create table
           Table table = new Table(tableModel.getColumnCount());
           
           // Add column headers to the table
           for (int i = 0; i < tableModel.getColumnCount(); i++) {
               table.addCell(tableModel.getColumnName(i));
           }
 
           // Add data to the table
           for (int row = 0; row < tableModel.getRowCount(); row++) {
               for (int col = 0; col < tableModel.getColumnCount(); col++) {
                   table.addCell(String.valueOf(tableModel.getValueAt(row, col)));
               }
           }
 
           // Add table to the document
           document.add(table);
           System.out.println("Stock report saved as PDF successfully.");
       } catch (Exception e) {
           System.err.println("Error generating PDF report: " + e.getMessage());
       }
   }                                     
