    private void updateTable() {
        // Clear existing rows
        tableModel.setRowCount(0);
    
        // Determine selected parameter
        String selectedParameter = (String) jComboBox1.getSelectedItem();
    
        // Determine user input
        String userInput = jTextField1.getText();
    
        // Load data based on the selected parameter and user input
        if (selectedParameter.equals("City")) {
            tableModel.setColumnIdentifiers(cityColumns);
            loadDataFromDatabase("SELECT * FROM stock WHERE city = '" + userInput + "'");
        } else if (selectedParameter.equals("Blood Center")) {
            tableModel.setColumnIdentifiers(centerColumns);
            loadDataFromDatabase("SELECT * FROM stock WHERE blood_center = '" + userInput + "'");
        } else if (selectedParameter.equals("Blood Type")) {
            tableModel.setColumnIdentifiers(typeColumns);
            loadDataFromDatabase("SELECT * FROM stock");
        }else if (selectedParameter.equals("Donation History")) {
            tableModel.setColumnIdentifiers(historyColumns);
            loadDataFromDatabase("SELECT * FROM adddonor");
        }
    }
    private void loadDataFromDatabase(String query) {
        // Modify this method to establish a database connection and fetch data
        try {
            //Connection conn = DriverManager.getConnection("jdbc:your_database_url", "username", "password");
            Connection conn = DbConnection.connect();
            PreparedStatement stmt = conn.prepareStatement(query);
            ResultSet rs = stmt.executeQuery();

            while (rs.next()) {
                Object[] rowData = new Object[tableModel.getColumnCount()];
                for (int i = 0; i < rowData.length; i++) {
                    rowData[i] = rs.getObject(i + 1);
                }
                tableModel.addRow(rowData);
            }

            rs.close();
            stmt.close();
            conn.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }

