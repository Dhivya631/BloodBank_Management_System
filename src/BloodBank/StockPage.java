    private void display(){
        try {
            Connection con=DbConnection.connect();
            String query="select * from stock";
            PreparedStatement st=con.prepareStatement(query);
            ResultSet result=st.executeQuery();
            DefaultTableModel model=new DefaultTableModel();
            model.addColumn("Blood Center");
            model.addColumn("City");
            model.addColumn("A+");
            model.addColumn("A-");
            model.addColumn("B+");
            model.addColumn("B-");
            model.addColumn("AB+");
            model.addColumn("AB-");
            model.addColumn("O+");
            model.addColumn("O-");
            while(result.next()){
                String blood_center= result.getString("blood_center");
                String city=result.getString("city");
                int units1= result.getInt("A+");
                int units2= result.getInt("A-");
                int units3= result.getInt("B+");
                int units4= result.getInt("B-");
                int units5= result.getInt("AB+");
                int units6= result.getInt("AB-");
                int units7= result.getInt("O+");
                int units8= result.getInt("O-");
                model.addRow(new Object[]{blood_center,city,units1,units2,units3,units4,units5,units6,units7,units8});
            }
            jTable1.setModel(model);
            con.close();
        }
        catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Error while updating","Error",JOptionPane.ERROR_MESSAGE);
        }
    }
