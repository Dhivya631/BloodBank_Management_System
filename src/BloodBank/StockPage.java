    private boolean isBloodCenterExists(String blood_center, String city){
        try{
            Connection con=DbConnection.connect();
            String query="select * from stock where blood_center =? and city =? ";
            PreparedStatement st=con.prepareStatement(query);
            st.setString(1, blood_center);
            st.setString(2, city);
            ResultSet result=st.executeQuery();
            if(result.next()){
                return true;
            }
            else{
                return false;
            }
        }
        catch(SQLException e){
            System.out.println("Error: "+e.getMessage());
        }
        return false;
    }
